export type IconName = keyof typeof ART | 'redo';

export function icon(name: IconName): SVGSVGElement {
  const rows: readonly string[] = name === 'redo' ? ART.undo.map((r) => [...r].reverse().join('')) : ART[name];
  let d = '';
  rows.forEach((r, y) => {
    for (const m of r.matchAll(/#+/g)) d += `M${m.index} ${y}h${m[0].length}v1h-${m[0].length}z`;
  });
  const svg = document.createElementNS('http://www.w3.org/2000/svg', 'svg');
  svg.setAttribute('viewBox', '0 0 11 11');
  svg.setAttribute('width', '22');
  svg.setAttribute('height', '22');
  svg.setAttribute('shape-rendering', 'crispEdges');
  svg.setAttribute('aria-hidden', 'true');
  const path = document.createElementNS('http://www.w3.org/2000/svg', 'path');
  path.setAttribute('d', d);
  path.setAttribute('fill', 'currentColor');
  svg.append(path);
  return svg;
}
